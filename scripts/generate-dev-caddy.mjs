#!/usr/bin/env node

import { readFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const moduleDirectory = dirname(fileURLToPath(import.meta.url));
const manifestPath = resolve(moduleDirectory, '..', 'config', 'edge', 'dev-access.json');
const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));

const exactKeys = (value, expected, label) => {
  const actual = Object.keys(value).sort();
  if (JSON.stringify(actual) !== JSON.stringify([...expected].sort())) {
    throw new Error(`${label} has an invalid shape`);
  }
};

exactKeys(
  manifest,
  [
    'browserIdentity',
    'browserRoutes',
    'host',
    'machineRoutes',
    'schemaVersion',
    'serviceRoutes',
    'staticRoot',
  ],
  'DEV edge manifest'
);
if (manifest.schemaVersion !== 1 || manifest.host !== 'dev.intexuraos.cloud') {
  throw new Error('DEV edge manifest identity is invalid');
}
if (manifest.browserIdentity !== 'kontakt@pbuchman.com') {
  throw new Error('DEV browser identity is invalid');
}

const lines = [
  '# Generated by scripts/generate-dev-caddy.mjs. Do not edit on the host.',
  `${manifest.host}:80 {`,
  '  log {',
  '    output file /var/log/caddy/intexuraos-dev-access.json {',
  '      roll_size 10MiB',
  '      roll_keep 90',
  '      roll_keep_for 2160h',
  '    }',
  '    format json',
  '  }',
  '  @noCache {',
  '    path / /index.html /sw.js /manifest.webmanifest',
  '  }',
  '  header @noCache Cache-Control "no-cache, no-store, must-revalidate"',
  '  @immutableAssets {',
  '    path /assets/* /workbox-*.js',
  '  }',
  '  header @immutableAssets Cache-Control "public, max-age=31536000, immutable"',
];

for (const [index, route] of manifest.machineRoutes.entries()) {
  exactKeys(route, ['guard', 'method', 'path', 'port', 'stripPrefix'], 'machine route');
  if (!/^(?:POST|PATCH)$/u.test(route.method) || !/^\/[-A-Za-z0-9_/]+$/u.test(route.path)) {
    throw new Error('Machine route method or path is invalid');
  }
  if (/[{}*]/u.test(route.path) || !route.path.startsWith(`${route.stripPrefix}/`)) {
    throw new Error('Machine route must use one literal path below its strip prefix');
  }
  lines.push(
    `  @machine${index} {`,
    `    method ${route.method}`,
    `    path ${route.path}`,
    '  }',
    `  handle @machine${index} {`,
    `    uri strip_prefix ${route.stripPrefix}`,
    `    reverse_proxy 127.0.0.1:${route.port}`,
    '  }',
    `  handle ${route.path} {`,
    '    respond "Method Not Allowed" 405',
    '  }'
  );
}

for (const route of manifest.browserRoutes) {
  exactKeys(route, ['pathPrefix', 'port'], 'browser route');
  if (!/^\/api\/[a-z0-9-]+$/u.test(route.pathPrefix)) {
    throw new Error('Browser route prefix is invalid');
  }
  lines.push(
    `  handle_path ${route.pathPrefix}/* {`,
    `    reverse_proxy 127.0.0.1:${route.port}`,
    '  }'
  );
}

for (const route of manifest.serviceRoutes) {
  exactKeys(route, ['guard', 'pathPrefix', 'port'], 'service route');
  if (
    route.guard !== 'cloudflare-service-auth-and-matrix-bearer' ||
    route.pathPrefix !== '/api/matrix-outbound' ||
    route.port !== 8099
  ) {
    throw new Error('Service route must be the exact Matrix outbound contract');
  }
  lines.push(
    `  handle_path ${route.pathPrefix}/* {`,
    `    reverse_proxy 127.0.0.1:${route.port}`,
    '  }'
  );
}

lines.push(
  '  @forbidden {',
  '    path /src/* /@vite/* /@fs/* /.env* *.map /webhook',
  '  }',
  '  handle @forbidden {',
  '    respond "Not Found" 404',
  '  }',
  '  handle {',
  `    root * ${manifest.staticRoot}`,
  '    try_files {path} /index.html',
  '    file_server',
  '  }',
  '}',
  ''
);

process.stdout.write(lines.join('\n'));
