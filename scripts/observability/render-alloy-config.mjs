#!/usr/bin/env node

const args = process.argv.slice(2);

function fail(message) {
  console.error(`ERROR: ${message}`);
  process.exit(1);
}

function parseArgs(argv) {
  const parsed = {
    environment: '',
    host: '',
    pm2LogGlob: '',
    output: '',
  };

  for (let index = 0; index < argv.length; index += 1) {
    const arg = argv[index];
    const next = argv[index + 1];

    if (arg === '--environment') {
      parsed.environment = next ?? '';
      index += 1;
    } else if (arg === '--host') {
      parsed.host = next ?? '';
      index += 1;
    } else if (arg === '--pm2-log-glob') {
      parsed.pm2LogGlob = next ?? '';
      index += 1;
    } else if (arg === '--output') {
      parsed.output = next ?? '';
      index += 1;
    } else if (arg === '--help' || arg === '-h') {
      console.log(
        'Usage: render-alloy-config.mjs --environment dev|prod --host HOST --pm2-log-glob /path/*.log [--output path]'
      );
      process.exit(0);
    } else {
      fail(`Unknown argument: ${arg ?? ''}`);
    }
  }

  return parsed;
}

function validate(input) {
  if (input.environment !== 'dev' && input.environment !== 'prod') {
    fail('--environment must be dev or prod');
  }
  if (!/^[A-Za-z0-9._-]+$/.test(input.host)) {
    fail('--host must contain only letters, numbers, dots, underscores, or dashes');
  }
  if (!input.pm2LogGlob.startsWith('/')) {
    fail('--pm2-log-glob must be an absolute path');
  }
  if (!input.pm2LogGlob.endsWith('*.log')) {
    fail('--pm2-log-glob must end with *.log');
  }
}

function alloyString(value) {
  return JSON.stringify(value);
}

function pathExcludeFor(logGlob) {
  return logGlob.replace(/\*\.log$/, '*.{gz,zip,bak,old}');
}

function render(input) {
  const pathExclude = pathExcludeFor(input.pm2LogGlob);

  return `// Generated by scripts/observability/render-alloy-config.mjs.
// Do not edit by hand.

logging {
  level = "info"
}

loki.source.file "pm2_logs" {
  targets = [
    {
      __path__         = ${alloyString(input.pm2LogGlob)},
      __path_exclude__ = ${alloyString(pathExclude)},
      project          = "intexuraos",
      environment      = ${alloyString(input.environment)},
      host             = ${alloyString(input.host)},
      job              = "pm2",
    },
  ]

  forward_to = [loki.relabel.pm2_labels.receiver]

  file_match {
    enabled     = true
    sync_period = "10s"
  }
}

loki.relabel "pm2_labels" {
  forward_to = [loki.process.pm2_logs.receiver]

  rule {
    source_labels = ["filename"]
    regex         = "^.*/(.+)-(out|error)(?:-[0-9]+)?\\\\.log$"
    target_label  = "service"
    replacement   = "$1"
  }

  rule {
    source_labels = ["filename"]
    regex         = "^.*/(.+)-(out|error)(?:-[0-9]+)?\\\\.log$"
    target_label  = "stream"
    replacement   = "$2"
  }

  rule {
    regex  = "^(project|environment|host|job|service|stream|filename)$"
    action = "labelkeep"
  }
}

loki.process "pm2_logs" {
  forward_to = [loki.write.grafana_cloud.receiver]

  stage.decolorize {}
}

loki.write "grafana_cloud" {
  endpoint {
    name     = "pm2_grafana_cloud"
    url      = sys.env("INTEXURAOS_GRAFANA_CLOUD_LOKI_URL")

    basic_auth {
      username = sys.env("INTEXURAOS_GRAFANA_CLOUD_LOKI_USERNAME")
      password = sys.env("INTEXURAOS_GRAFANA_CLOUD_LOKI_TOKEN")
    }
  }
}
`;
}

const input = parseArgs(args);
validate(input);
const output = render(input);

if (input.output) {
  const { writeFileSync } = await import('node:fs');
  writeFileSync(input.output, output, { mode: 0o644 });
} else {
  process.stdout.write(output);
}
